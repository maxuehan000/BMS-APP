uint16_t  Accumulation(uint8_t *buf,uint16_t len)
{
    uint16_t i,sum;
    sum = 0;
    for(i=0;i<len;i++)
        sum += *(buf+i);
    return sum;    
}
void ShortHLSwap(u8 *bytes)
{
    u8 swap;
    swap = *bytes;
    *bytes = *(bytes+1);
    *(bytes+1) = swap;
}
void int4byteHLSwap(u8 *bytes)
{
    unsigned long long timebuf;
    u8 i;
    timebuf = 0;
    for(i=0;i<4;i++)
    {
        timebuf <<= 8;
        timebuf += (unsigned char) *(bytes+3-i);
    }
    for(i=0;i<4;i++)
    { 
        *(bytes+3-i) = timebuf&0xff;
        timebuf >>= 8;
    }
}
