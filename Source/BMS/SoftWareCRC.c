u16 Crc16Calc(u8 data_In, u16 PreCheckSum)
{
	u16 crc16;

	crc16 = PreCheckSum;
	crc16= (u16)((crc16>> 8) | (crc16<< 8));
	crc16^= data_In;
	crc16^= (u16)((crc16& 0xFF) >> 4);
	crc16^= (u16)((crc16<< 8) << 4);
	crc16^= (u16)(((crc16& 0xFF) << 4) << 1);

	return crc16;
}

